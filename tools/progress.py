"""Rebuild PROGRESS.md from the `Status:` line in every exercise file.

Book exercises are r/c/p files (r01_04.py is R-1.4). Real-world exercises are
w files (w01_06_3.py is W-1.6.3) and come first within each chapter.

Usage:
    python tools/progress.py          # rebuild PROGRESS.md
    python tools/progress.py --next   # also print the next 5 exercises to do
"""
import re
import sys
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHAPTERS = ROOT / "chapters"
OUT = ROOT / "PROGRESS.md"
FILE_RE = re.compile(r"^(?:([rcp])(\d{2})_(\d{2})|(w)(\d{2})_(\d{2})_(\d{1,2}))\.py$")
ORDER = {"W": 0, "R": 1, "C": 2, "P": 3}  # real-world first, then the book's order
STATUS_RE = re.compile(r"^Status:\s*([\w-]+)", re.M)
DATE_RE = re.compile(r"^Date:\s*(\d{4}-\d{2}-\d{2})", re.M)
TITLE_RE = re.compile(r"^# Chapter \d+: (.+)$", re.M)


def scan():
    rows = []
    for f in sorted(CHAPTERS.rglob("*.py")):
        m = FILE_RE.match(f.name)
        if not m:
            continue
        if m.group(4):
            kind, ch, n, sub = "W", int(m.group(5)), int(m.group(6)), int(m.group(7))
            ex_id = f"W-{ch}.{n}.{sub}"
        else:
            kind, ch, n, sub = m.group(1).upper(), int(m.group(2)), int(m.group(3)), 0
            ex_id = f"{kind}-{ch}.{n}"
        head = f.read_text(encoding="utf-8")[:1500]
        s = STATUS_RE.search(head)
        d = DATE_RE.search(head)
        rows.append({
            "id": ex_id, "kind": kind, "ch": ch, "n": n, "sub": sub,
            "status": s.group(1).lower() if s else "todo",
            "date": d.group(1) if d else None,
            "path": f.relative_to(ROOT).as_posix(),
        })
    return sorted(rows, key=lambda r: (r["ch"], ORDER[r["kind"]], r["n"], r["sub"]))


def bar(done, total, width=20):
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def streak(dates):
    """Consecutive weekdays (ending today or the last weekday) with at least one exercise done."""
    days = {date.fromisoformat(d) for d in dates}
    day = date.today()
    while day.weekday() >= 5 or (day == date.today() and day not in days):
        day -= timedelta(days=1)
    count = 0
    while day in days or day.weekday() >= 5:
        if day.weekday() < 5:
            count += 1
        day -= timedelta(days=1)
    return count


def main():
    rows = scan()
    titles = {}
    for readme in CHAPTERS.glob("ch*/README.md"):
        ch = int(readme.parent.name[2:4])
        t = TITLE_RE.search(readme.read_text(encoding="utf-8"))
        titles[ch] = t.group(1) if t else readme.parent.name

    done = [r for r in rows if r["status"] == "done"]
    skipped = [r for r in rows if r["status"] == "skipped"]
    active = len(rows) - len(skipped)
    dated = [r["date"] for r in done if r["date"]]
    todo = [r for r in rows if r["status"] in ("todo", "in-progress")]

    per = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for r in rows:
        if r["status"] == "skipped":
            continue
        per[r["ch"]][r["kind"]][1] += 1
        if r["status"] == "done":
            per[r["ch"]][r["kind"]][0] += 1

    lines = [
        "# Progress",
        "",
        "_Auto-generated by `python tools/progress.py`. Don't edit by hand._",
        "",
        f"**Overall:** `{bar(len(done), active)}` {len(done)}/{active} "
        f"({100 * len(done) / active:.1f}%) · skipped: {len(skipped)}",
        "",
        f"**Sessions logged:** {len(set(dated))} · **Weekday streak:** {streak(dated)} · "
        f"**Last session:** {max(dated) if dated else 'none yet'}",
        "",
        "| Ch | Topic | Real-world | Reinforcement | Creativity | Projects | Progress |",
        "|---:|---|:---:|:---:|:---:|:---:|---|",
    ]
    for ch in sorted(per):
        k = per[ch]
        d = sum(v[0] for v in k.values())
        t = sum(v[1] for v in k.values())
        cell = lambda x: f"{k[x][0]}/{k[x][1]}" if k[x][1] else "–"
        lines.append(f"| {ch} | {titles.get(ch, '')} | {cell('W')} | {cell('R')} | {cell('C')} | "
                     f"{cell('P')} | `{bar(d, t, 10)}` {100 * d / t:.0f}% |")

    lines += ["", "## Up next", ""]
    lines += [f"- [ ] **{r['id']}** ({r['status']}) [`{r['path']}`]({r['path']})" for r in todo[:5]]
    if not todo:
        lines.append("Nothing left. You finished the book! 🎉")

    recent = sorted((r for r in done if r["date"]), key=lambda r: r["date"], reverse=True)[:10]
    if recent:
        lines += ["", "## Recently completed", ""]
        lines += [f"- {r['date']}: **{r['id']}**" for r in recent]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PROGRESS.md updated: {len(done)}/{active} done")
    if "--next" in sys.argv:
        print("Next up:", ", ".join(r["id"] for r in todo[:5]) or "nothing")


if __name__ == "__main__":
    main()
